#!/usr/bin/env bash
# Ubuntu/Linux: allow or ignore incoming IPv4 and IPv6 ICMP Echo Requests.
# Only controls echo replies (ping). Does not disable the IP protocols,
# IPv6 Neighbor Discovery, or other necessary ICMP/ICMPv6 messages.
set -euo pipefail

KEY_IPV4='net.ipv4.icmp_echo_ignore_all'
KEY_IPV6='net.ipv6.icmp.echo_ignore_all'
CONF='/etc/sysctl.d/99-ping-control.conf'

usage() {
  cat <<'USAGE'
Usage: sudo bash ping-control.sh {disable|enable|status} [--persist]

  disable   Ignore incoming IPv4 and IPv6 ping (Echo Request) packets.
  enable    Allow kernel replies to incoming IPv4 and IPv6 ping packets.
  status    Show current IPv4/IPv6 ping response settings.
  --persist Save the new settings across reboots (disable/enable only).

Note: Other firewall and cloud security-group rules may still block ping.
USAGE
}

get_value() {
  sysctl -n "$1" 2>/dev/null
}

show_status() {
  local label="$1" key="$2" value
  if value="$(get_value "$key")"; then
    case "$value" in
      1) printf '%s: DISABLED (kernel ignores Echo Requests)\n' "$label" ;;
      0) printf '%s: ENABLED by sysctl (firewall may still block)\n' "$label" ;;
      *) printf '%s: UNKNOWN (value: %s)\n' "$label" "$value" ;;
    esac
  else
    printf '%s: UNAVAILABLE (protocol/module/sysctl not present)\n' "$label"
  fi
}

if (( $# < 1 || $# > 2 )); then
  usage
  exit 2
fi

ACTION="$1"
PERSIST="${2:-}"
if [[ -n "$PERSIST" && "$PERSIST" != '--persist' ]]; then
  usage
  exit 2
fi

case "$ACTION" in
  status)
    if [[ -n "$PERSIST" ]]; then usage; exit 2; fi
    show_status 'IPv4 ping' "$KEY_IPV4"
    show_status 'IPv6 ping' "$KEY_IPV6"
    if [[ -f "$CONF" ]]; then
      printf '\nPersistent configuration: %s\n' "$CONF"
      cat "$CONF"
    else
      echo 'No persistent configuration created by this script.'
    fi
    exit 0
    ;;
  disable) VALUE=1 ;;
  enable)  VALUE=0 ;;
  *) usage; exit 2 ;;
esac

if (( EUID != 0 )); then
  echo 'Error: root privileges required. Use sudo.' >&2
  exit 1
fi

# IPv4 is expected on Ubuntu; fail rather than silently claim success.
if ! get_value "$KEY_IPV4" >/dev/null; then
  echo "Error: IPv4 sysctl unavailable: $KEY_IPV4" >&2
  exit 1
fi

# Check availability before changing any settings.
HAS_IPV6=0
if get_value "$KEY_IPV6" >/dev/null; then
  HAS_IPV6=1
fi

sysctl -w "${KEY_IPV4}=${VALUE}"
if (( HAS_IPV6 )); then
  sysctl -w "${KEY_IPV6}=${VALUE}"
else
  echo "Notice: IPv6 sysctl unavailable; skipping $KEY_IPV6" >&2
fi

if [[ "$PERSIST" == '--persist' ]]; then
  # Use a single atomic file replacement to avoid partial writes.
  TMP_FILE="$(mktemp /etc/sysctl.d/.99-ping-control.XXXXXXXX)"
  trap 'rm -f "$TMP_FILE"' EXIT
  {
    echo '# Generated by ping-control.sh: incoming Echo Requests only.'
    printf '%s = %s\n' "$KEY_IPV4" "$VALUE"
    if (( HAS_IPV6 )); then
      printf '%s = %s\n' "$KEY_IPV6" "$VALUE"
    fi
  } > "$TMP_FILE"
  chmod 0644 "$TMP_FILE"
  mv -f "$TMP_FILE" "$CONF"
  trap - EXIT
  printf 'Persistent settings saved: %s\n' "$CONF"
else
  echo 'Runtime settings changed. Reboot persistence is not guaranteed.'
fi

printf '\n'
show_status 'IPv4 ping' "$KEY_IPV4"
show_status 'IPv6 ping' "$KEY_IPV6"
