CREATE TABLE ftp_download_task (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    task_uuid VARCHAR(36) NOT NULL,
    user_id BIGINT NOT NULL,
    protocol VARCHAR(20) NOT NULL,
    host VARCHAR(253) NOT NULL,
    port INT NOT NULL,
    remote_path VARCHAR(4096) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    total_bytes BIGINT NULL,
    downloaded_bytes BIGINT NOT NULL DEFAULT 0,
    expected_sha256 CHAR(64) NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    execution_epoch BIGINT NOT NULL DEFAULT 0,
    retry_count INT NOT NULL DEFAULT 0,
    next_retry_at DATETIME NULL,
    last_error_code VARCHAR(64) NULL,
    last_error_message VARCHAR(500) NULL,
    completed_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted BIGINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_ftp_task_uuid_deleted (task_uuid, deleted),
    KEY idx_ftp_task_user_status (user_id, status, deleted),
    KEY idx_ftp_task_user_created (user_id, created_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE ftp_task_credential (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    task_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    auth_mode VARCHAR(20) NOT NULL,
    encrypted_username TEXT NULL,
    encrypted_password TEXT NULL,
    username_nonce VARCHAR(64) NULL,
    password_nonce VARCHAR(64) NULL,
    key_id VARCHAR(64) NULL,
    cipher_version INT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted BIGINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_ftp_credential_task_deleted (task_id, deleted),
    KEY idx_ftp_credential_user_task (user_id, task_id, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE ftp_transfer_checkpoint (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    task_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    local_key VARCHAR(512) NOT NULL,
    remote_size BIGINT NULL,
    remote_mtime VARCHAR(64) NULL,
    remote_unique_id VARCHAR(255) NULL,
    committed_bytes BIGINT NOT NULL DEFAULT 0,
    local_sha256 CHAR(64) NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    last_verified_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted BIGINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_ftp_checkpoint_task_deleted (task_id, deleted),
    KEY idx_ftp_checkpoint_user_task (user_id, task_id, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
